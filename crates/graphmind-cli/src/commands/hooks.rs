use graphmind_config::{Registry, resolve_project_slug};
use colored::Colorize;
use std::fs;
#[cfg(unix)]
use std::os::unix::fs::PermissionsExt;
use std::path::Path;

const POST_COMMIT_HOOK: &str = r#"#!/bin/sh
# graphmind: auto-rebuild
export PATH="$HOME/.graphmind/bin:$HOME/.local/bin:/usr/local/bin:$PATH"

graphmind build 2>/dev/null &
"#;

const PRE_PUSH_HOOK: &str = "#!/bin/sh\n# graphmind: diff-impact\nexport PATH=\"$HOME/.graphmind/bin:$HOME/.local/bin:/usr/local/bin:$PATH\"\necho \"\"\necho \"  graphmind diff-impact:\"\ngraphmind diff-impact 2>/dev/null\necho \"\"\n";

// After `git pull` / `git merge`: files changed without a commit of ours.
const POST_MERGE_HOOK: &str = r#"#!/bin/sh
# graphmind: rebuild after merge/pull
export PATH="$HOME/.graphmind/bin:$HOME/.local/bin:/usr/local/bin:$PATH"

graphmind build 2>/dev/null &
"#;

// After `git rebase` / `git commit --amend` ($1 = rebase|amend).
const POST_REWRITE_HOOK: &str = r#"#!/bin/sh
# graphmind: rebuild after rebase/amend
export PATH="$HOME/.graphmind/bin:$HOME/.local/bin:/usr/local/bin:$PATH"

graphmind build 2>/dev/null &
"#;

/// The hook scripts graphmind installs, in install order.
const HOOKS: [(&str, &str); 5] = [
    ("post-commit", POST_COMMIT_HOOK),
    ("pre-push", PRE_PUSH_HOOK),
    ("post-checkout", POST_CHECKOUT_HOOK),
    ("post-merge", POST_MERGE_HOOK),
    ("post-rewrite", POST_REWRITE_HOOK),
];

/// Where git runs this repo's hooks from, and whether graphmind may write there.
enum HooksLocation {
    /// The repo's own git dir (`.git/hooks`, shared by its worktrees): safe to edit.
    GitDir(std::path::PathBuf),
    /// `core.hooksPath` points inside the work tree (husky, a tracked `.githooks/`): files there
    /// are versioned or regenerated by a tool, so editing them changes the team's repo or gets
    /// undone. `edit_dir` is where the person should add the lines.
    InWorkTree { edit_dir: std::path::PathBuf, husky: bool },
    /// `core.hooksPath` points outside the repo (a global hooks folder): editing it would
    /// affect every repository on the machine.
    Shared(std::path::PathBuf),
}

fn locate_hooks(project_path: &Path) -> Option<HooksLocation> {
    use graphmind_config::git_identity;
    let hooks = git_identity::hooks_dir(project_path)?;
    let common = git_identity::common_dir(project_path)?;
    if hooks.starts_with(&common) {
        return Some(HooksLocation::GitDir(hooks));
    }
    match git_identity::toplevel(project_path) {
        Some(top) if hooks.starts_with(&top) => {
            // husky v9 points core.hooksPath at its generated `.husky/_`; the scripts people
            // edit are `.husky/<hook>`.
            let husky = hooks.components().any(|c| c.as_os_str() == ".husky");
            let edit_dir = if husky { top.join(".husky") } else { hooks };
            Some(HooksLocation::InWorkTree { edit_dir, husky })
        }
        _ => Some(HooksLocation::Shared(hooks)),
    }
}

/// The graphmind lines of a hook script (without the shebang), for manual setups.
fn hook_lines(content: &str) -> String {
    content.lines().filter(|l| !l.starts_with("#!")).collect::<Vec<_>>().join("\n").trim().to_string()
}

fn print_manual_instructions(dir: &Path, why: &str) {
    println!("  {} {}", "!".yellow(), why);
    println!("  Not changed. To rebuild the graph automatically, add these lines yourself:\n");
    for (name, content) in HOOKS {
        println!("  {}", dir.join(name).display().to_string().bold());
        for line in hook_lines(content).lines() {
            println!("    {line}");
        }
        println!();
    }
}

// git passes $1=previous HEAD, $2=new HEAD, $3=1 for a branch checkout (0
// for a plain file checkout) — only reindex on an actual branch switch. An
// all-zero $1 is a brand-new checkout (`git worktree add`): a plain build there
// registers the worktree and seeds its graph from the main checkout's.
const POST_CHECKOUT_HOOK: &str = r#"#!/bin/sh
# graphmind: reindex on branch switch and new worktrees
export PATH="$HOME/.graphmind/bin:$HOME/.local/bin:/usr/local/bin:$PATH"

if [ "$3" = "1" ]; then
  if [ -z "$(printf '%s' "$1" | tr -d 0)" ]; then
    graphmind build 2>/dev/null &
  else
    graphmind build --changed "$1" "$2" 2>/dev/null &
  fi
fi
"#;

fn install_hook(hooks_dir: &Path, name: &str, content: &str) -> bool {
    let hook_path = hooks_dir.join(name);

    if hook_path.exists() {
        let existing = fs::read_to_string(&hook_path).unwrap_or_default();
        if existing.contains("graphmind") {
            let is_outdated = existing.contains("memory add \"[commit]")
                || existing.contains("memory add '[commit]");
            if is_outdated {
                // Backup before overwriting
                graphmind_config::back_up(&hook_path).ok();
                fs::write(&hook_path, content).ok();
                println!("  {}: updated (removed outdated patterns)", name.dimmed());
            } else {
                println!("  {}: already installed", name.dimmed());
                return false;
            }
        } else {
            // Backup before appending
            graphmind_config::back_up(&hook_path).ok();
            let stripped: String = content
                .lines()
                .filter(|l| !l.starts_with("#!"))
                .collect::<Vec<_>>()
                .join("\n");
            fs::write(&hook_path, format!("{existing}\n{stripped}")).ok();
        }
    } else {
        fs::write(&hook_path, content).ok();
    }

    #[cfg(unix)]
    fs::set_permissions(&hook_path, fs::Permissions::from_mode(0o755)).ok();
    true
}

/// Adds the hooks introduced since graphmind's hooks were installed in each registered
/// repo (post-checkout, post-merge, post-rewrite). Run by `setup`, which re-runs after
/// an upgrade. Only repos whose own git dir already has graphmind's post-commit hook:
/// this completes an install people chose, it never starts one. Returns the number of
/// repos updated.
pub fn refresh_installed() -> usize {
    let mut seen = std::collections::HashSet::new();
    let mut updated = 0;
    for project in Registry::list() {
        let Some(HooksLocation::GitDir(dir)) = locate_hooks(Path::new(&project.path)) else {
            continue;
        };
        // Worktrees of one repo share its hooks.
        if !seen.insert(dir.clone()) {
            continue;
        }
        let ours = |name: &str| fs::read_to_string(dir.join(name)).is_ok_and(|b| b.contains("graphmind"));
        if !ours("post-commit") {
            continue;
        }
        let mut added = false;
        for (name, content) in HOOKS {
            if !ours(name) {
                added |= install_hook(&dir, name, content);
            }
        }
        if added {
            updated += 1;
        }
    }
    updated
}

pub fn install(slug: Option<&str>) {
    let slug = match resolve_project_slug(&[slug]) {
        Some(s) => s,
        None => {
            eprintln!("{} Not in a registered project.", "Error:".red().bold());
            std::process::exit(1);
        }
    };

    let project = match Registry::get(&slug) {
        Some(p) => p,
        None => {
            eprintln!("{} Project \"{}\" not found.", "Error:".red().bold(), slug);
            std::process::exit(1);
        }
    };

    let project_path = Path::new(&project.path);
    let hooks_dir = match locate_hooks(project_path) {
        Some(HooksLocation::GitDir(dir)) => dir,
        Some(HooksLocation::InWorkTree { edit_dir, husky }) => {
            let why = if husky {
                "This repo runs its git hooks through husky (core.hooksPath).".to_string()
            } else {
                format!("This repo's git hooks are files in the repo ({}).", edit_dir.display())
            };
            print_manual_instructions(&edit_dir, &why);
            return;
        }
        Some(HooksLocation::Shared(dir)) => {
            let why = format!(
                "Git hooks come from a shared folder for all repos (core.hooksPath = {}).",
                dir.display()
            );
            print_manual_instructions(&dir, &why);
            return;
        }
        None => {
            eprintln!("{} No .git directory in {}", "Error:".red().bold(), project.path);
            std::process::exit(1);
        }
    };
    fs::create_dir_all(&hooks_dir).ok();

    let mut installed = 0;
    for (name, content) in HOOKS {
        if install_hook(&hooks_dir, name, content) {
            installed += 1;
        }
    }

    if installed > 0 {
        println!(
            "{} Installed {} hook(s) for \"{}\"",
            "OK".green().bold(),
            installed,
            slug
        );
    } else {
        println!("{}", "All hooks already installed.".dimmed());
    }
}

pub fn uninstall(slug: Option<&str>) {
    let slug = match resolve_project_slug(&[slug]) {
        Some(s) => s,
        None => {
            eprintln!("{} Not in a registered project.", "Error:".red().bold());
            std::process::exit(1);
        }
    };

    let project = match Registry::get(&slug) {
        Some(p) => p,
        None => {
            eprintln!("{} Project \"{}\" not found.", "Error:".red().bold(), slug);
            std::process::exit(1);
        }
    };

    // Only the repo's own git dir: graphmind never writes into managed or shared hook folders.
    let hooks_dir = match locate_hooks(Path::new(&project.path)) {
        Some(HooksLocation::GitDir(dir)) => dir,
        _ => {
            println!("{}", "No graphmind hooks found.".dimmed());
            return;
        }
    };
    let mut removed = 0;

    for (name, _) in HOOKS {
        let hook_path = hooks_dir.join(name);
        if !hook_path.exists() {
            continue;
        }

        let content = match fs::read_to_string(&hook_path) {
            Ok(c) => c,
            Err(_) => continue,
        };

        if !content.contains("graphmind") {
            continue;
        }

        let filtered: Vec<&str> = content
            .lines()
            .filter(|l| !l.contains("graphmind"))
            .collect();

        let remaining = filtered
            .iter()
            .filter(|l| !l.trim().is_empty() && l.trim() != "#!/bin/sh")
            .count();

        if remaining == 0 {
            fs::remove_file(&hook_path).ok();
        } else {
            fs::write(&hook_path, filtered.join("\n")).ok();
        }
        removed += 1;
    }

    if removed > 0 {
        println!(
            "{} Removed graphmind hooks from \"{}\"",
            "OK".green().bold(),
            slug
        );
    } else {
        println!("{}", "No graphmind hooks found.".dimmed());
    }
}
